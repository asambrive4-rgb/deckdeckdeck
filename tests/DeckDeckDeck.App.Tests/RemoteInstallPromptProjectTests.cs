    [Fact]
    public void SettingsRepositoryPersistsRecentRemoteInstallProjectsAcrossReloads()
    {
        var appDataPath = Path.Combine(Path.GetTempPath(), $"deck_recent_{Guid.NewGuid():N}");
        try
        {
            var services = CreateServices(appDataPath);
            services.SettingsRepository.RecordRecentRemoteInstallProject(@"C:\Projects\FirstApp");
            services.SettingsRepository.RecordRecentRemoteInstallProject(@"C:\Projects\SecondApp");
            services.SettingsRepository.RecordRecentRemoteInstallProject(@"C:\Projects\FirstApp\");

            var reloaded = CreateServices(services.Storage.AppDataPath).SettingsRepository.Load();

            Assert.Equal(
                [@"C:\Projects\FirstApp", @"C:\Projects\SecondApp"],
                reloaded.RecentRemoteInstallProjects.ToArray());
        }
        finally
        {
            SqliteConnection.ClearAllPools();
            if (Directory.Exists(appDataPath))
            {
                Directory.Delete(appDataPath, recursive: true);
            }
        }
    }

