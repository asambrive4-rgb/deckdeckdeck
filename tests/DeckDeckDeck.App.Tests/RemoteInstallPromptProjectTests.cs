    [Fact]
    public void RemoteInstallRulesTitleAndRecentProjectHistoryBehaveAsExpected()
    {
        var promptTitle = RemoteInstallRules.RecommendDefaultSlotTitle(null, RemoteInstallDeviceKind.Watch, promptProject: true);
        Assert.Equal("워치 원격설치 (선택)", promptTitle);
        Assert.True(RemoteInstallRules.IsAutoGeneratedSlotTitle(promptTitle));
        Assert.True(RemoteInstallRules.IsAutoGeneratedSlotTitle("태블릿·폰 원격설치 (선택)"));

        var existing = new List<string>
        {
            @"C:\Projects\App1",
            @"C:\Projects\App2",
            @"C:\Projects\App3",
            @"C:\Projects\App4",
            @"C:\Projects\App5",
            @"C:\Projects\App6"
        };

        // Prepending App3 with mixed casing and trailing slash moves it to index 0 without duplicates.
        var updated = RemoteInstallRules.PrependRecentProjectPath(existing, @" c:\projects\app3\ ");
        Assert.Equal(6, updated.Count);
        Assert.Equal(@"c:\projects\app3", updated[0]);
        Assert.Equal(@"C:\Projects\App1", updated[1]);
        Assert.DoesNotContain(updated.Skip(1), p => string.Equals(p, @"C:\Projects\App3", StringComparison.OrdinalIgnoreCase));

        var roundTripped = RemoteInstallRules.ParseRecentProjectPaths(RemoteInstallRules.SerializeRecentProjectPaths(updated));
        Assert.Equal(updated, roundTripped);
    }

    [Fact]
    public async Task ExecuteSnippetActionUseCasePromptsRecentFiveBuildsAllListAndRecordsSelection()
    {
        var services = CreateServices();
        var category = services.CategoryRepository.Create(SlotKey.Numpad1, "개발", null);

        // Seed another category slot with an extra project not in recent history
        services.SnippetRepository.Create(category.Id, SlotKey.Numpad4, new SnippetSaveData(
            Title: "태블릿 고정",
            Content: string.Empty,
            Description: null,
            ImagePath: null,
            ThumbnailPath: null,
            ActionType: SnippetActionType.RemoteInstall,
            RemoteInstallProjectPath: @"C:\Projects\OtherSlotProject",
            RemoteInstallModule: ":app",
            RemoteInstallDeviceKind: RemoteInstallDeviceKind.Tablet));

        // Save 7 recent projects -> prompt must show top 5 as RecentProjects, and full list in AllProjects
        var recentHistory = new[]
        {
            @"C:\Projects\Recent1",
            @"C:\Projects\Recent2",
            @"C:\Projects\Recent3",
            @"C:\Projects\Recent4",
            @"C:\Projects\Recent5",
            @"C:\Projects\Recent6",
            @"C:\Projects\Recent7"
        };
        var initialSettings = services.SettingsRepository.Load();
        initialSettings.RecentRemoteInstallProjects = recentHistory;
        services.SettingsRepository.Save(initialSettings);

        var promptSnippet = services.SnippetRepository.Create(category.Id, SlotKey.Numpad5, new SnippetSaveData(
            Title: "폰 원격설치 (선택)",
            Content: string.Empty,
            Description: null,
            ImagePath: null,
            ThumbnailPath: null,
            ActionType: SnippetActionType.RemoteInstall,
            RemoteInstallDeviceKind: RemoteInstallDeviceKind.Phone,
            RemoteInstallTargetDevice: "192.168.0.22:5555",
            RemoteInstallLaunchAfterInstall: false,
            RemoteInstallPromptProject: true));

        var dialog = new PromptRemoteInstallDialogStub
        {
            SelectionToReturn = new RemoteInstallProjectSelection(@"C:\Projects\ChosenApp\", ":phone:android")
        };
        var gateway = new SpyRemoteInstallGateway
        {
            DiscoveredProjects = [@"C:\Projects\DiscoveredApp", @"C:\Projects\Recent2"]
        };

        var useCase = new ExecuteSnippetActionUseCase(
            new RecordingClipboardPasteGateway(),
            new RecordingFileLaunchGatewayAdapter(),
            new RecordingUrlLaunchGatewayAdapter(),
            new RecordingSystemMediaActionGatewayAdapter(),
            new RecordingSpotifyMediaActionGatewayAdapter(),
            new RecordingTerminalCommandGatewayAdapter(),
            new RecordingFilePasteGateway(),
            dialog,
            androidRemoteInstallGateway: gateway,
            settingsRepository: services.SettingsRepository,
            snippetRepository: services.SnippetRepository);

        var result = await useCase.ExecuteAsync(new ExecuteSnippetActionRequest(
            ExecutableAction.FromSnippet(promptSnippet),
            new AppSettings { AutoHideAfterPaste = true },
            IntPtr.Zero));

        Assert.True(result.Succeeded);
        Assert.True(result.ShouldHideWindow);
        Assert.NotNull(dialog.LastRequest);
        Assert.Equal(5, dialog.LastRequest!.RecentProjects.Count);
        Assert.Equal(
            [@"C:\Projects\Recent1", @"C:\Projects\Recent2", @"C:\Projects\Recent3", @"C:\Projects\Recent4", @"C:\Projects\Recent5"],
            dialog.LastRequest.RecentProjects.Select(static p => p.ProjectPath).ToArray());

        // AllProjects contains all 7 recent + OtherSlotProject + DiscoveredApp (deduped Recent2) = 9
        Assert.Equal(9, dialog.LastRequest.AllProjects.Count);
        Assert.Contains(dialog.LastRequest.AllProjects, p => p.ProjectPath == @"C:\Projects\OtherSlotProject");
        Assert.Contains(dialog.LastRequest.AllProjects, p => p.ProjectPath == @"C:\Projects\DiscoveredApp");

        Assert.NotNull(gateway.LastRequest);
        Assert.Equal(@"C:\Projects\ChosenApp", gateway.LastRequest!.ProjectPath);
        Assert.Equal(":phone:android", gateway.LastRequest.ModuleName);
        Assert.Equal(RemoteInstallDeviceKind.Phone, gateway.LastRequest.TargetDeviceKind);
        Assert.Equal("192.168.0.22:5555", gateway.LastRequest.TargetDeviceFilter);
        Assert.False(gateway.LastRequest.LaunchAfterInstall);
        Assert.Equal("ChosenApp · 폰", gateway.LastRequest.Title);

        // Reload persisted settings from a fresh repository check via service Load
        var updatedSettings = services.SettingsRepository.Load();
        Assert.Equal(@"C:\Projects\ChosenApp", updatedSettings.RecentRemoteInstallProjects[0]);
    }

