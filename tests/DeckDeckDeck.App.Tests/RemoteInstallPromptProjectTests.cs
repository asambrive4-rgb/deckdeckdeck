    [Fact]
    public void RemoteInstallProjectPickerWindowMeasuresCleanlyWithRecentFiveAndEmptyStates()
    {
        Exception? exception = null;
        var thread = new Thread(() =>
        {
            try
            {
                var app = System.Windows.Application.Current ?? new System.Windows.Application();
                var themeUri = new Uri("/DeckDeckDeck.App;component/Resources/Theme.xaml", UriKind.Relative);
                if (!app.Resources.MergedDictionaries.Any(d => d.Source == themeUri))
                {
                    app.Resources.MergedDictionaries.Add(new ResourceDictionary { Source = themeUri });
                }

                var recent = Enumerable.Range(1, 5)
                    .Select(i => new RemoteInstallProjectCandidate($@"C:\Projects\App{i}", $"App{i}", IsRecent: true, SourceBadge: "최근 사용"))
                    .ToList();
                var all = recent
                    .Concat([new RemoteInstallProjectCandidate(@"C:\Projects\ExtraApp", "ExtraApp", IsRecent: false, SourceBadge: "AndroidStudioProjects")])
                    .ToList();

                var withRecent = new RemoteInstallProjectPickerWindow(new RemoteInstallProjectPromptRequest(
                    SlotTitle: "폰 원격설치 (선택)",
                    TargetDeviceKind: RemoteInstallDeviceKind.Phone,
                    TargetDeviceFilter: null,
                    RecentProjects: recent,
                    AllProjects: all,
                    ScanModules: _ =>
                    [
                        new AndroidAppModuleInfo(":phone:android", @"C:\Projects\App1\phone\android", "com.example.phone"),
                        new AndroidAppModuleInfo(":wear:android", @"C:\Projects\App1\wear\android", "com.example.wear")
                    ]));

                withRecent.Measure(new System.Windows.Size(540, 760));
                withRecent.Arrange(new Rect(0, 0, 540, 760));
                withRecent.UpdateLayout();

                var emptyRecent = new RemoteInstallProjectPickerWindow(new RemoteInstallProjectPromptRequest(
                    SlotTitle: "워치 원격설치 (선택)",
                    TargetDeviceKind: RemoteInstallDeviceKind.Watch,
                    TargetDeviceFilter: null,
                    RecentProjects: [],
                    AllProjects: all,
                    ScanModules: _ => [new AndroidAppModuleInfo(":app", @"C:\Projects\ExtraApp\app", "com.example.app")]));

                emptyRecent.Measure(new System.Windows.Size(540, 760));
                emptyRecent.Arrange(new Rect(0, 0, 540, 760));
                emptyRecent.UpdateLayout();
            }
            catch (Exception ex)
            {
                exception = ex;
            }
            finally
            {
                if (System.Windows.Application.Current?.Dispatcher.CheckAccess() == true)
                {
                    System.Windows.Application.Current.Shutdown();
                }
                Dispatcher.CurrentDispatcher.InvokeShutdown();
            }
        });

        thread.SetApartmentState(ApartmentState.STA);
        thread.Start();
        thread.Join();

        Assert.Null(exception);
    }
